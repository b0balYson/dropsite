var updateDoc = flag.Bool("update", false, "rewrite the tool inventory in docs/mcp-tools.md")

const (
	toolsDoc   = "../../docs/mcp-tools.md"
	docBegin   = "<!-- tools:begin (generated by `go test ./internal/mcp -run TestToolsDoc -update`) -->"
	docEnd     = "<!-- tools:end -->"
	sizesBegin = "<!-- sizes:begin -->"
	sizesEnd   = "<!-- sizes:end -->"
)

// TestToolsDoc keeps the tool inventory of docs/mcp-tools.md equal to the
// tools both servers offer (deploy_files remote, deploy_folder local).
func TestToolsDoc(t *testing.T) {
	cs := connect(t, NewServer("test", func(context.Context, *sdk.CallToolRequest) (Backend, error) {
		return newFake(), nil
	}, Options{Files: true, Folder: true, SiteFiles: true, Forms: true, Cabinet: true, Collections: true,
		Workflow: true, Drafts: true, Instructions: Instructions}))
	list, err := cs.ListTools(context.Background(), nil)
	if err != nil {
		t.Fatal(err)
	}
	doc, err := os.ReadFile(toolsDoc)
	if err != nil {
		t.Fatal(err)
	}
	text := replaceBlock(t, string(doc), docBegin, docEnd, toolsTable(t, list.Tools))
	text = replaceBlock(t, text, sizesBegin, sizesEnd, sizes(t, list))
	if *updateDoc {
		if err := os.WriteFile(toolsDoc, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if text != string(doc) {
		t.Errorf("%s is out of date: run `go test ./internal/mcp -run TestToolsDoc -update`", toolsDoc)
	}
}

func replaceBlock(t *testing.T, doc, begin, end, body string) string {
	t.Helper()
	before, rest, ok := strings.Cut(doc, begin)
	_, after, ok2 := strings.Cut(rest, end)
	if !ok || !ok2 {
		t.Fatalf("%s lacks %s ... %s", toolsDoc, begin, end)
	}
	return before + begin + "\n" + body + end + after
}

// sizes reports the bytes a client receives for tools/list (the remote tool
// set) and for the server instructions.
func sizes(t *testing.T, list *sdk.ListToolsResult) string {
	t.Helper()
	remote := *list
	remote.Tools = nil
	for _, tl := range list.Tools {
		if tl.Name != "deploy_folder" {
			remote.Tools = append(remote.Tools, tl)
		}
	}
	b, err := json.Marshal(remote)
	if err != nil {
		t.Fatal(err)
	}
	var desc int
	for _, tl := range remote.Tools {
		desc += len(tl.Description)
	}
	return fmt.Sprintf("- tools/list of the remote server: %d tools, about %d KB of JSON, of which %d KB are descriptions\n"+
		"- server instructions: %d bytes (limit 4096)\n", len(remote.Tools), (len(b)+512)/1024, (desc+512)/1024,
		len(Instructions))
}

func toolsTable(t *testing.T, tools []*sdk.Tool) string {
	t.Helper()
	sort.Slice(tools, func(i, j int) bool { return tools[i].Name < tools[j].Name })
	var b strings.Builder
	b.WriteString("| Tool | Hints | Input (* required) | Output | Description |\n| --- | --- | --- | --- | --- |\n")
	for _, tl := range tools {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", tl.Name, hints(tl.Annotations),
			inputCell(t, tl.InputSchema), outputCell(t, tl.OutputSchema), cell(tl.Description))
	}
	return b.String()
}

func hints(a *sdk.ToolAnnotations) string {
	switch {
	case a.ReadOnlyHint:
		return "read-only"
	case a.DestructiveHint != nil && *a.DestructiveHint && a.IdempotentHint:
		return "destructive, idempotent"
	case a.DestructiveHint != nil && *a.DestructiveHint:
		return "destructive"
	case a.IdempotentHint:
		return "write, idempotent"
	}
	return "write"
}

func inputCell(t *testing.T, s any) string {
	m := schemaMap(t, s)
	required := map[string]bool{}
	if r, ok := m["required"].([]any); ok {
		for _, v := range r {
			required[v.(string)] = true
		}
	}
	props, _ := m["properties"].(map[string]any)
	names := make([]string, 0, len(props))
	for name := range props {
		names = append(names, name)
	}
	sort.Strings(names)
	parts := make([]string, 0, len(names))
	for _, name := range names {
		p := "`" + name + "`"
		if required[name] {
			p += "*"
		}
		if enum, ok := props[name].(map[string]any)["enum"].([]any); ok && len(enum) <= 6 {
			vals := make([]string, 0, len(enum))
			for _, v := range enum {
				if v != "" {
					vals = append(vals, fmt.Sprint(v))
				}
			}
			p += " (" + strings.Join(vals, ", ") + ")"
		}
		parts = append(parts, p)
	}
	if len(parts) == 0 {
		return "none"
	}
	return strings.Join(parts, ", ")
}

func outputCell(t *testing.T, s any) string {
	props := properties(t, s)
	names := make([]string, 0, len(props))
	for name := range props {
		names = append(names, "`"+name+"`")
	}
	sort.Strings(names)
	return strings.Join(names, ", ")
}

func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ", "<", "&lt;", ">", "&gt;").Replace(s)
}
